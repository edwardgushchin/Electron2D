"""Generate the theme's compiled native type catalog from the public API inventory."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "src/Scene/Resources/ThemeDB.Types.cs"


def generate(records):
    types = {row["declaringType"]: row for row in records if row["kind"] == "type"}

    def is_native(name):
        while name in types:
            if name == "Electron2D.ElectronObject":
                return True
            name = types[name].get("baseType")
        return False

    selected = sorted(name for name in types if "<" not in name and is_native(name))
    entries = "\n".join(f"        typeof(global::{name})," for name in selected)
    return ("// Generated by tools/coverage/theme_types.py from the compiled public type inventory.\n"
            "namespace Electron2D;\n\npublic sealed partial class ThemeDB\n{\n"
            "    private static readonly Dictionary<string, Type> NativeTypes = new Type[]\n    {\n"
            + entries + "\n    }.ToDictionary(type => type.Name, StringComparer.Ordinal);\n}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate(json.loads((ROOT / "docs/coverage/data/electron2d.json").read_text()))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit("The compiled native theme catalog is stale; run tools/coverage/theme_types.py.")
    else:
        OUTPUT.write_text(text)
