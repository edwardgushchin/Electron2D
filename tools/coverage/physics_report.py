"""Physics audit scope; states come from the ordinary coverage classifier."""

from collections import Counter


ROOTS = frozenset("""
CollisionObject2D Shape2D Joint2D CollisionShape2D CollisionPolygon2D RayCast2D
ShapeCast2D PhysicsMaterial PhysicsServer2D PhysicsServer2DExtension
PhysicsServer2DManager PhysicsDirectBodyState2D PhysicsDirectSpaceState2D
PhysicsRayQueryParameters2D PhysicsPointQueryParameters2D PhysicsShapeQueryParameters2D
PhysicsTestMotionParameters2D PhysicsTestMotionResult2D KinematicCollision2D World2D
SkeletonModification2DPhysicalBones SkeletonModification2DJiggle
""".split())

# Shared consumers are selected by declared name, including overloads. Everything
# inherited by these consumers is accounted for in the separate base-class group.
CROSS_NAMES = {
    "Viewport": {"physics_object_picking", "physics_object_picking_first_only", "physics_object_picking_sort",
                 "physics_interpolation_mode"},
    "Performance": {"get_monitor", "PHYSICS_2D_ACTIVE_OBJECTS", "PHYSICS_2D_COLLISION_PAIRS", "PHYSICS_2D_ISLAND_COUNT"},
    "SceneTree": {"debug_collisions_hint", "physics_interpolation", "physics_frame"},
    "Engine": {"get_physics_frames", "get_physics_interpolation_fraction", "is_in_physics_frame",
               "max_physics_steps_per_frame", "physics_jitter_fix", "physics_ticks_per_second", "time_scale"},
    "TileMapLayer": {"get_coords_for_body_rid", "has_body_rid", "collision_enabled",
                     "collision_visibility_mode", "physics_quadrant_size", "use_kinematic_bodies",
                     "DebugVisibilityMode", "DEBUG_VISIBILITY_MODE_DEFAULT",
                     "DEBUG_VISIBILITY_MODE_FORCE_HIDE", "DEBUG_VISIBILITY_MODE_FORCE_SHOW"},
}
CROSS_PREFIXES = {
    "TileSet": ("add_physics_", "get_physics_", "move_physics_", "remove_physics_", "set_physics_"),
    "TileData": ("add_collision_", "get_collision_", "is_collision_", "remove_collision_", "set_collision_",
                 "get_constant_", "set_constant_"),
    "ProjectSettings": ("physics/2d/", "physics/common/", "debug/shapes/collision/"),
}
STATES = ("Implemented", "Partial", "Blocked", "Unimplemented", "Excluded")


def scope(types):
    lookup = {item["name"]: item for item in types}
    missing = (ROOTS | CROSS_NAMES.keys() | CROSS_PREFIXES.keys()) - lookup.keys()
    if missing:
        raise ValueError(f"Physics audit types missing from pin: {sorted(missing)}")
    families = set(ROOTS)
    while True:
        descendants = {name for name, item in lookup.items() if item["inherits"] in families} - families
        if not descendants:
            break
        families.update(descendants)
    cross = {}
    for name in CROSS_NAMES.keys() | CROSS_PREFIXES.keys():
        members = lookup[name]["members"]
        unknown = CROSS_NAMES.get(name, set()) - {m["name"] for m in members}
        if unknown:
            raise ValueError(f"Physics audit declarations missing from {name}: {sorted(unknown)}")
        selected = {m["id"] for m in members if m["name"] in CROSS_NAMES.get(name, ())
                    or m["name"].startswith(CROSS_PREFIXES.get(name, ()))}
        if not selected:
            raise ValueError(f"Empty physics audit consumer: {name}")
        cross[name] = selected
    bases = set()
    for name in families | cross.keys():
        parent = lookup[name]["inherits"]
        while parent:
            if parent not in families:
                bases.add(parent)
            parent = lookup[parent]["inherits"]
    # A selected consumer can also be an inherited base; count its complete
    # declaration family once in that case, never duplicate a declaration ID.
    return families, bases, {n: ids for n, ids in cross.items() if n not in bases}


def render_physics(upstream, classified, coverage_target):
    families, bases, cross = scope(upstream["types"])
    groups = (("Physics families and descendants", families),
              ("Shared inherited declarations", bases),
              ("Cross-domain physics consumers", set(cross)))
    lookup = {item["name"]: item for item in upstream["types"]}
    lines = ["# Physics declaration audit", "", "Generated by `tools/coverage/render.py`; do not edit.", "",
             f"Reference: `{upstream['godot_version']}` at `{upstream['godot_commit']}`.", "",
             "[Source and behavior audit](../components/physics-contract-audit.md) explains the backend boundary, missing behavior and acceptance work.", "",
             "States are reused from the class tables, including accepted representation/deprecation exclusions. "
             "Implemented records existing runtime evidence; it does **not** certify an independent GPU backend. "
             "Class and enum rows are included: counts are declarations, not feature counts or completion percentages.", "",
             "The scope takes every descendant of the explicit physics roots, follows the full inheritance chain, "
             "and adds selected settings, picking, debug and tile consumers. Shared base rows are counted once; "
             "they remain requirements of the inherited public contract. General consumer API is linked from its class page. "
             "Deprecated TileMap is superseded by TileMapLayer; renderer particle effects and 3D physics are outside this solver scope.", ""]
    seen = set()
    for heading, names in groups:
        lines.extend([f"## {heading}", "", "| Declaring type | Base | " + " | ".join(STATES) + " |",
                      "| --- | --- | " + " | ".join("---:" for _ in STATES) + " |"])
        open_rows = []
        totals = Counter()
        for name in sorted(names):
            rows = classified[name]
            if heading == "Cross-domain physics consumers":
                rows = [row for row in rows if row[0] in cross[name]]
            counts = Counter()
            for identity, state, reason in rows:
                if identity in seen:
                    raise ValueError(f"Duplicate physics audit declaration: {identity}")
                seen.add(identity)
                counts[state] += 1
                if state not in {"Implemented", "Excluded"}:
                    open_rows.append((name, identity, state, reason))
            totals.update(counts)
            base = lookup[name]["inherits"]
            base_link = f"[{base}](classes/{coverage_target(base)})" if base else "—"
            lines.append(f"| [{name}](classes/{coverage_target(name)}) | {base_link} | "
                         + " | ".join(str(counts[state]) for state in STATES) + " |")
        lines.extend(["| **Total** | | " + " | ".join(str(totals[state]) for state in STATES) + " |", "",
                      "Every open declaration in this group follows. Its class table retains mapped signatures, "
                      "source links, implemented evidence and exact exclusion reasons.", "",
                      "| Declaration | State | Missing behavior / evidence |", "| --- | --- | --- |"])
        for name, identity, state, reason in open_rows:
            lines.append(f"| [`{identity}`](classes/{coverage_target(name)}) | {state} | {reason.replace('|', '&#124;')} |")
        lines.append("")
    return "\n".join(lines)
