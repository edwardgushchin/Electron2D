#!/usr/bin/env python3
"""Generate fixed locale tables and typed plural selectors from the pinned comparison data."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[2]
SHA256 = 'd58b78a6bb8bcb883167e7566c7954f80f1459127d656f715e9a081e753a106f'


def rows(source, name):
    body = re.search(r'static const char \*' + name + r'\[\]\[\d\] = \{(.*?)\n\};', source, re.S)[1]
    return [[json.loads(value) for value in re.findall(r'"(?:\\.|[^"\\])*"', row)]
            for row in re.findall(r'\{([^{}]*)\}', body) if 'nullptr' not in row]


class Expression:
    # A build-time translation of this fixed arithmetic grammar, never runtime code evaluation.
    def __init__(self, text):
        self.tokens = re.findall(r'\d+|n|==|!=|<=|>=|&&|\|\||[()?:%<>]', text)
        assert ''.join(self.tokens) == re.sub(r'\s+', '', text)
        self.position = 0

    def take(self, token):
        if self.position < len(self.tokens) and self.tokens[self.position] == token:
            self.position += 1
            return True
        return False

    def parse(self, level=0):
        operations = [['?'], ['||'], ['&&'], ['==', '!='], ['<', '>', '<=', '>='], ['%']]
        if level == len(operations):
            if self.take('('):
                value = self.parse()
                assert self.take(')')
                return value
            token = self.tokens[self.position]
            self.position += 1
            assert token == 'n' or token.isdecimal()
            return token, False
        value = self.parse(level + 1)
        while self.position < len(self.tokens) and self.tokens[self.position] in operations[level]:
            operation = self.tokens[self.position]
            self.position += 1
            if operation == '?':
                yes = self.parse()
                assert self.take(':')
                no = self.parse()
                value = f'({self.boolean(value)} ? {self.numeric(yes)} : {self.numeric(no)})', False
            else:
                other = self.parse(level + 1)
                convert = self.boolean if operation in ['&&', '||'] else self.numeric
                value = f'({convert(value)} {operation} {convert(other)})', operation != '%'
        return value

    @staticmethod
    def numeric(value):
        return f'({value[0]} ? 1 : 0)' if value[1] else value[0]

    @staticmethod
    def boolean(value):
        return value[0] if value[1] else f'({value[0]} != 0)'


def generate(source):
    output = ['// <auto-generated />', 'namespace Electron2D;', '', 'internal static class LocaleCatalog', '{']
    for name, original, reverse in [('Languages', 'language_list', False), ('Scripts', 'script_list', True),
                                    ('Countries', 'country_names', False), ('LanguageRenames', 'locale_renames', False),
                                    ('CountryRenames', 'country_renames', False), ('Variants', 'locale_variants', False)]:
        output += [f'    internal static readonly Dictionary<string, string> {name} = new(StringComparer.Ordinal)', '    {']
        for key, value in rows(source, original):
            if reverse:
                key, value = value, key
            output.append(f'        [{json.dumps(key, ensure_ascii=False)}] = {json.dumps(value, ensure_ascii=False)},')
        output += ['    };']
    output += ['    internal static readonly (string Language, string Script, string DefaultCountry, string Countries)[] Defaults =', '    [']
    output += ['        (' + ', '.join(json.dumps(v) for v in row) + '),' for row in rows(source, 'locale_scripts')]
    output += ['    ];', '    internal static readonly Dictionary<string, (string Definition, int Forms, Func<long, int> Select)> Plurals = CreatePlurals();',
               '    private static Dictionary<string, (string Definition, int Forms, Func<long, int> Select)> CreatePlurals()', '    {',
               '        var result = new Dictionary<string, (string Definition, int Forms, Func<long, int> Select)>(StringComparer.Ordinal);']
    for locales, definition in rows(source, 'plural_rules'):
        # The four two-form predicates select singular; gettext form zero is singular.
        if locales in ['is mk', 'tzm', 'am as bn doi fa gu hi kn pcm zu', 'ceb fil tl']:
            condition = re.fullmatch(r'nplurals=2; plural=(.*);', definition)[1]
            definition = f'nplurals=2; plural=({condition} ? 0 : 1);'
        forms, expression = re.fullmatch(r'nplurals=(\d+); plural=(.*);', definition).groups()
        parser = Expression(expression)
        code = parser.numeric(parser.parse())
        assert parser.position == len(parser.tokens)
        output += [f'        foreach (var locale in {json.dumps(locales)}.Split(\' \'))',
                   f'            result[locale] = ({json.dumps(definition)}, {forms}, static n => {code});']
    output += ['        return result;', '    }', '}', '']
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = args.source.read_bytes()
    assert hashlib.sha256(data).hexdigest() == SHA256, 'Pinned locale input differs.'
    text = generate(data.decode())
    target = ROOT / 'src/Core/String/LocaleCatalog.Generated.cs'
    if args.check:
        assert target.read_text() == text, 'Locale catalog is stale.'
    else:
        target.write_text(text)
    print('Locale metadata and plural selectors verified.')


if __name__ == '__main__':
    main()
