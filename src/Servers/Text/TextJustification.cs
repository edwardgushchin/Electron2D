    /// <summary>Returns the scalar preceding inserted elongation, or minus one when no opportunity exists.</summary>
    internal static int FindKashida(ReadOnlySpan<uint> text, int start, int end)
    {
        if ((uint)start > (uint)text.Length || end < start || end > text.Length) throw new ArgumentOutOfRangeException(nameof(start));
        while (end > start && Contains(TransparentRanges, text[end - 1])) end--;
        var result = -1; var priority = 100; uint previous = 0;
        for (var i = start; i < end; i++)
        {
            var scalar = text[i]; var group = JoiningGroup(scalar); var last = i == end - 1;
            var connected = i > start && Contains(ConnectingRanges, previous) && !(JoiningGroup(previous) == Group.Lam && group == Group.Alef);
            var candidate = scalar == 0x0640 ? 0 :
                group == Group.SeenSad && !last && text[i + 1] != 0x200C ? 1 :
                connected && (group is Group.TehMarbuta or Group.Dal || group == Group.Heh && last) ? 2 :
                connected && (group == Group.Alef || last && group is Group.Lam or Group.Tah or Group.Kaf or Group.Gaf) ? 3 :
                connected && !last && group is Group.Beh or Group.BehYeh && JoiningGroup(text[i + 1]) is Group.Reh or Group.Yeh or Group.BehYeh ? 4 :
                connected && (group == Group.Waw || last && group is Group.Ain or Group.Qaf or Group.Feh) ? 5 :
                connected && group == Group.Reh ? 6 : 101;
            if (candidate <= priority) { result = candidate <= 1 ? i : i - 1; priority = candidate; }
            if (!Contains(TransparentRanges, scalar)) previous = scalar;
        }
        return result;
    }

    private static bool Contains(ReadOnlySpan<uint> ranges, uint scalar)
    {
        var low = 0; var high = ranges.Length / 2 - 1;
        while (low <= high)
        {
            var middle = (low + high) / 2; var index = middle * 2;
            if (scalar < ranges[index]) high = middle - 1;
            else if (scalar > ranges[index + 1]) low = middle + 1;
            else return true;
        }
        return false;
    }

