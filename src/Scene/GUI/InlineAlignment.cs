namespace Electron2D;

/// <summary>Aligns an inline object against its text line.</summary>
public enum InlineAlignment
{
    /// <summary>baseline to.</summary>
    BaselineTo = 3,
    /// <summary>bottom.</summary>
    Bottom = 14,
    /// <summary>bottom to.</summary>
    BottomTo = 2,
    /// <summary>center.</summary>
    Center = 5,
    /// <summary>center to.</summary>
    CenterTo = 1,
    /// <summary>image mask.</summary>
    ImageMask = 3,
    /// <summary>text mask.</summary>
    TextMask = 12,
    /// <summary>top.</summary>
    Top = 0,
    /// <summary>top to.</summary>
    TopTo = 0,
    /// <summary>to baseline.</summary>
    ToBaseline = 8,
    /// <summary>to bottom.</summary>
    ToBottom = 12,
    /// <summary>to center.</summary>
    ToCenter = 4,
    /// <summary>to top.</summary>
    ToTop = 0,
}
